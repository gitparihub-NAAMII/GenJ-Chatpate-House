const NE_DIGITS = '०१२३४५६७८९';
function t(key) {
  const lang = (window.LOCAL && LOCAL.lang) || 'en';
  return (I18N[lang] && I18N[lang][key]) ?? I18N.en[key] ?? key;
}
function num(n) {
  const s = String(n);
  if ((window.LOCAL && LOCAL.lang) !== 'ne') return s;
  return s.replace(/[0-9]/g, d => NE_DIGITS[d]);
}
function rs(n) { return (LOCAL.lang === 'ne' ? 'रु. ' : 'Rs. ') + num(Math.round(n * 100) / 100); }
